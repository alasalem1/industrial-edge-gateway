import numpy as np
from pathlib import Path
from sklearn.ensemble import IsolationForest

rng = np.random.default_rng(2027)

data = np.genfromtxt(
    "ml/datasets/normal_operation.csv",
    delimiter=",",
    skip_header=1
)
rng.shuffle(data)

split = int(len(data) * 0.8)
train, holdout = data[:split], data[split:]

model = IsolationForest(
    n_estimators=128,
    max_samples=256,
    contamination="auto",
    random_state=42,
    n_jobs=1
)
model.fit(train)

# Calibrate at 1% false alarms using independent normal samples.
threshold = float(np.quantile(model.score_samples(holdout), 0.01))

offsets = []
features = []
thresholds = []
left = []
right = []
samples = []

for estimator in model.estimators_:
    tree = estimator.tree_
    offsets.append(len(features))

    features.extend(tree.feature.tolist())
    thresholds.extend(tree.threshold.tolist())
    left.extend(tree.children_left.tolist())
    right.extend(tree.children_right.tolist())
    samples.extend(tree.n_node_samples.tolist())

offsets.append(len(features))

def array(name, ctype, values, formatter=str, per_line=12):
    lines = [f"static const {ctype} {name}[{len(values)}] = {{"]
    for start in range(0, len(values), per_line):
        part = values[start:start + per_line]
        lines.append("    " + ", ".join(formatter(v) for v in part) + ",")
    lines.append("};")
    return "\n".join(lines)

header = [
    "/* Generated by ml/export_model.py. Do not edit manually. */",
    "#ifndef SENTINEL_ISOLATION_FOREST_MODEL_H",
    "#define SENTINEL_ISOLATION_FOREST_MODEL_H",
    "",
    "#define SENTINEL_AI_TREE_COUNT 128",
    "#define SENTINEL_AI_MAX_SAMPLES 256",
    f"#define SENTINEL_AI_NODE_COUNT {len(features)}",
    f"#define SENTINEL_AI_THRESHOLD ({threshold:.17g})",
    "",
    array("sentinel_ai_tree_offsets", "int", offsets),
    array("sentinel_ai_features", "short", features),
    array("sentinel_ai_thresholds", "double", thresholds,
          lambda x: f"{x:.17g}", 4),
    array("sentinel_ai_left", "int", left),
    array("sentinel_ai_right", "int", right),
    array("sentinel_ai_samples", "int", samples),
    "",
    "#endif"
]

output = Path("sentinel-edge-ui/src/ml/isolation_forest_model.h")
output.write_text("\n\n".join(header) + "\n")

print("===== MODEL EXPORT =====")
print("Training samples:", len(train))
print("Calibration samples:", len(holdout))
print("Trees:", len(model.estimators_))
print("Total tree nodes:", len(features))
print("Nodes per tree: min={}, max={}".format(
    min(offsets[i+1] - offsets[i] for i in range(128)),
    max(offsets[i+1] - offsets[i] for i in range(128))
))
print("Calibrated threshold:", f"{threshold:.9f}")
print("Generated:", output)
print("Header size:", f"{output.stat().st_size / 1024:.1f} KiB")
